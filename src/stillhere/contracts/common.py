"""Types shared by more than one contract group: data origin, sources, model references, chat messages."""
from __future__ import annotations

from dataclasses import dataclass, fields, is_dataclass
from datetime import datetime
from enum import Enum
from typing import Any, List, Optional, Tuple

from ._base import Contract, ValidationError, require_id, require_sha256, require_text


class DataOrigin(str, Enum):
    """Where a piece of data came from. Only ``synthetic`` may appear in the public repository."""

    SYNTHETIC = "synthetic"  # fully invented, describes no real person
    SIMULATED = "simulated"  # model- or author-generated content about a real persona (private line only)
    REAL = "real"            # authorised real data (private line only)


class SourceKind(str, Enum):
    CONVERSATION = "conversation"
    DOCUMENT = "document"
    INTERVIEW = "interview"
    MANUAL_ANNOTATION = "manual_annotation"
    SCRIPT = "script"          # a hand-written synthetic script
    SIMULATION = "simulation"  # generated by a simulation process


class Role(str, Enum):
    SYSTEM = "system"
    USER = "user"
    ASSISTANT = "assistant"


@dataclass(frozen=True)
class SourceRef(Contract):
    """A citable origin for persona traits or memories.

    ``locator`` says where the source can be found (a relative path, a URI). In the private line it may be
    a private path; such records never enter this repository.
    """

    source_id: str
    kind: SourceKind
    origin: DataOrigin
    description: str
    created_at: Optional[datetime] = None
    locator: Optional[str] = None
    sha256: Optional[str] = None

    def validate(self) -> None:
        require_id("source_id", self.source_id)
        require_text("description", self.description)
        if self.sha256 is not None:
            require_sha256("sha256", self.sha256)


@dataclass(frozen=True)
class Provenance(Contract):
    """Links a memory to the exact source it was derived from."""

    source_id: str
    locator: Optional[str] = None       # e.g. "turn:3" inside a conversation source
    quote: Optional[str] = None         # short supporting excerpt
    observed_at: Optional[datetime] = None

    def validate(self) -> None:
        require_id("source_id", self.source_id)
        if self.locator is not None:
            require_text("locator", self.locator)


@dataclass(frozen=True)
class ModelRef(Contract):
    """Identifies a base model. ``locator`` is a runtime path and is optional in manifests."""

    model_id: str                 # e.g. "Qwen/Qwen3-8B"
    revision: Optional[str] = None
    dtype: Optional[str] = None
    locator: Optional[str] = None

    def validate(self) -> None:
        require_text("model_id", self.model_id)


@dataclass(frozen=True)
class PromptTemplateRef(Contract):
    """Names the chat template used to render prompts. Training and inference must use the same one."""

    name: str
    version: str
    sha256: Optional[str] = None  # hash of the rendered template definition, once one exists

    def validate(self) -> None:
        require_id("name", self.name)
        require_text("version", self.version)
        if self.sha256 is not None:
            require_sha256("sha256", self.sha256)


@dataclass(frozen=True)
class AdapterRef(Contract):
    """A LoRA/QLoRA adapter and the base model and template it was trained against."""

    adapter_id: str
    base_model: ModelRef
    prompt_template: PromptTemplateRef
    origin: DataOrigin            # origin of the data it was trained on
    method: str = "qlora"
    sha256: Optional[str] = None  # hash of the adapter weights file
    locator: Optional[str] = None

    def validate(self) -> None:
        require_id("adapter_id", self.adapter_id)
        require_text("method", self.method)
        if self.sha256 is not None:
            require_sha256("sha256", self.sha256)


@dataclass(frozen=True)
class ChatMessage(Contract):
    """One chat turn. A turn is one or more bubbles (separately sent messages)."""

    role: Role
    bubbles: Tuple[str, ...]
    created_at: Optional[datetime] = None
    message_id: Optional[str] = None

    def validate(self) -> None:
        if not self.bubbles:
            raise ValidationError("ChatMessage.bubbles must contain at least one bubble")
        for i, b in enumerate(self.bubbles):
            require_text(f"ChatMessage.bubbles[{i}]", b)
        if self.message_id is not None:
            require_id("message_id", self.message_id)

    @property
    def text(self) -> str:
        """Bubbles joined by newlines. Prompt templates may choose a different separator."""
        return "\n".join(self.bubbles)


class PublicBoundaryError(ValidationError):
    """Raised when non-synthetic data is found where only synthetic data is allowed."""


def find_non_synthetic(obj: Any, path: str = "$") -> List[str]:
    """Return the paths of every ``DataOrigin`` value in ``obj`` that is not ``synthetic``."""
    hits: List[str] = []
    if isinstance(obj, DataOrigin):
        if obj is not DataOrigin.SYNTHETIC:
            hits.append(f"{path}={obj.value}")
    elif is_dataclass(obj) and not isinstance(obj, type):
        for f in fields(obj):
            hits += find_non_synthetic(getattr(obj, f.name), f"{path}.{f.name}")
    elif isinstance(obj, (list, tuple)):
        for i, v in enumerate(obj):
            hits += find_non_synthetic(v, f"{path}[{i}]")
    return hits


def assert_public_safe(obj: Any) -> None:
    """Fail unless every origin inside ``obj`` is synthetic. Use before writing anything to the public repo."""
    hits = find_non_synthetic(obj)
    if hits:
        raise PublicBoundaryError("non-synthetic data in a public artefact: " + "; ".join(hits))
