def build_notebook() -> dict:
    cells = []
    for kind, src in NB.CELLS:
        lines = src.strip("\n").splitlines(keepends=True)
        if kind == "markdown":
            cells.append({"cell_type": "markdown", "metadata": {}, "source": lines})
        else:
            cells.append({"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [], "source": lines})
    return {"cells": cells, "metadata": {"accelerator": "GPU", "colab": {"gpuType": "A100", "provenance": []},
                                         "kernelspec": {"display_name": "Python 3", "name": "python3"}, "language_info": {"name": "python"}},
            "nbformat": 4, "nbformat_minor": 0}


def write_notebook(path: Path = NOTEBOOK) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(build_notebook(), ensure_ascii=False, indent=1) + "\n", encoding="utf-8", newline="\n")
    return path


def git(*args) -> str:
    return subprocess.check_output(["git", "-C", str(ROOT), *args], text=True).strip()


def code_zip(dest: Path) -> list:
    raw = subprocess.check_output(["git", "-C", str(ROOT), "archive", "--format=zip", "HEAD", *SHIPPED])
    files = []
    with zipfile.ZipFile(io.BytesIO(raw)) as src, zipfile.ZipFile(dest, "w", zipfile.ZIP_DEFLATED) as out:
        for info in src.infolist():
            if info.is_dir():
                continue
            name = info.filename
            if any(x in name for x in ("/private/", ".env", ".sqlite", ".safetensors", "__pycache__", ".jsonl")):
                raise SystemExit(f"refusing to ship {name}")
            out.writestr(name, src.read(info))
            files.append(name)
    return files


def token_plan(pilot: Path) -> dict:
    meta = {json.loads(l)["id"]: json.loads(l) for l in (pilot / "pilot_train_meta.jsonl").read_text(encoding="utf-8").splitlines() if l.strip()}
    plans = {}
    for prof, f, ga in (("c8192", "pilot_train.jsonl", 8), ("c4096", "pilot_train_le4096.jsonl", 8)):
        ids = [json.loads(l)["id"] for l in (pilot / "train" / f).read_text(encoding="utf-8").splitlines() if l.strip()]
        rows = [meta[i] for i in ids]
        inp = sum(r["input_tokens"] for r in rows)
        sup = sum(r["supervised_tokens"] for r in rows)
        by = {}
        for r in rows:
            by.setdefault(r["source"], [0, 0])
            by[r["source"]][0] += r["input_tokens"] + r["supervised_tokens"]
            by[r["source"]][1] += r["supervised_tokens"]
        plans[prof] = {"rows": len(rows), "steps": -(-len(rows) // ga), "epochs": 1, "micro_batch": 1, "grad_accum": ga,
                       "input_tokens": inp, "supervised_tokens": sup, "total_tokens": inp + sup, "padding_waste_tokens": 0,
                       "padding_note": "micro-batch 1 and packing off: no padding inside a batch", "rows_over_4000_input": sum(r["input_tokens"] > 4000 for r in rows),
                       "long_share": round(sum(r["input_tokens"] > 4000 for r in rows) / max(1, len(rows)), 4),
                       "token_share_by_source": {s: round(v[0] / max(1, inp + sup), 4) for s, v in sorted(by.items())},
                       "supervised_share_by_source": {s: round(v[1] / max(1, sup), 4) for s, v in sorted(by.items())}}
    return plans


